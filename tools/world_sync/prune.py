#!/usr/bin/env python3
"""Drop the world-sync data upstream now covers. Run after merging upstream.

Needs nothing but this repository (no GRFs, no Divine Pride key):
  - db/re/mob_db_world.yml: monsters whose Id or AegisName upstream's
    mob_db now has (upstream's entry wins anyway, as mob_db_world loads first;
    this keeps the two from merging drops and skills), and their rows in
    the world-sync block of db/re/mob_skill_db.txt
  - the world-sync blocks of db/map_index.txt and conf/maps_athena.conf:
    maps upstream now lists itself (else "Map already loaded!")
  - npc/re/world_sync/*.txt: spawns on maps upstream now spawns, scripts or
    turned off, and links out of maps upstream now uses
Prints what it removed; exits 1 if it removed anything, so CI can say so.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import generate  # noqa: E402


def entries(text):
    head, _, body = text.partition('\nBody:\n')
    return head + '\nBody:\n', re.split(r'\n(?=  - Id: )', body.strip('\n')) if body.strip() else []


def main():
    root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..'))
    removed = []

    # monsters
    official = open(os.path.join(root, 'db', 're', 'mob_db.yml'), encoding='utf-8').read()
    ids = set(int(i) for i in re.findall(r'^  - Id: (\d+)', official, re.M))
    aegis = set(re.findall(r'^    AegisName: (\S+)', official, re.M))
    p = os.path.join(root, 'db', 're', 'mob_db_world.yml')
    gone = set()
    if os.path.exists(p):
        head, body = entries(open(p, encoding='utf-8').read())
        keep = []
        for e in body:
            m = re.match(r'  - Id: (\d+)\n    AegisName: (\S+)', e)
            if m and (int(m.group(1)) in ids or m.group(2) in aegis):
                gone.add(int(m.group(1)))
                removed.append('monster %s %s' % m.groups())
            else:
                keep.append(e)
        if gone:
            open(p, 'w', encoding='utf-8', newline='\n').write(head + '\n'.join(keep) + '\n')
    sk = os.path.join(root, 'db', 're', 'mob_skill_db.txt')
    text = open(sk, encoding='utf-8', errors='surrogateescape').read()
    mark = '\n// World sync (GENERATED by tools/world_sync/divine_pride.py'
    if gone and mark in text:
        before, _, block = text.partition(mark)
        lines = block.split('\n')
        kept = [lines[0]] + [l for l in lines[1:] if not (re.match(r'(\d+),', l) and int(l.split(',')[0]) in gone)]
        open(sk, 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(before + mark + '\n'.join(kept))

    # maps
    maps, ours, s_npcs, s_mobs, s_warps, mobdb, mobclass = generate.server_world(root)
    idx = os.path.join(root, 'db', 'map_index.txt')
    t = open(idx, errors='replace').read()
    official_idx = set(re.findall(r'^([a-z0-9_@.\-]+)', t.split('\n' + generate.MARK)[0], re.M))
    ours_idx = re.findall(r'^([a-z0-9_@.\-]+)', t.split('\n' + generate.MARK)[1], re.M) if generate.MARK in t else []
    for m in sorted(set(ours_idx) & (official_idx | maps)):
        removed.append('map %s' % m)
    generate.set_block(idx, ['%s\n' % m for m in ours_idx if m not in official_idx and m not in maps])
    conf = os.path.join(root, 'conf', 'maps_athena.conf')
    generate.set_block(conf, ['map: %s\n' % m for m in sorted(ours)])   # server_world already left out upstream's

    # spawns and links
    touched, warped = generate.touched_maps(root)
    used = touched | warped | {n[0] for n in s_npcs} | {w[0] for w in s_warps} | {w[3] for w in s_warps}
    for fn, test in (('spawns.txt', lambda mp: mp in used and mp not in ours),
                     ('warps.txt', lambda mp: mp in used and mp not in ours),
                     ('transports.txt', lambda mp: mp in used and mp not in ours)):
        p = os.path.join(root, 'npc', 're', 'world_sync', fn)
        if not os.path.exists(p):
            continue
        text = open(p, encoding='cp949', errors='replace').read()
        blocks = re.split(r'\n(?=[a-z0-9_@.\-]+,\d+,\d+)', text)
        keep = []
        for b in blocks:
            m = re.match(r'([a-z0-9_@.\-]+),\d+,\d+', b)
            if m and test(m.group(1)):
                removed.append('%s %s' % (fn, b.split('\n')[0][:80]))
            else:
                keep.append(b)
        if len(keep) != len(blocks):
            open(p, 'w', encoding='cp949', errors='replace', newline='\n').write('\n'.join(keep))

    for r in removed:
        print('removed', r)
    print('%d removed' % len(removed))
    sys.exit(1 if removed else 0)


if __name__ == '__main__':
    main()
